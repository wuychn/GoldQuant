"""Source Protocol definitions for market data."""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class DailySource(Protocol):
    """日线库数据源规范（构建/维护离线库的原子拉取）。

    所有方法只用 ≤ 当前可获取数据，返回归一化 schema（daily_raw / index_daily）。
    实现内部负责重试退避（``_shared._retry``）+ 限速（``source_headers`` 策略）。
    默认实现 ``DefaultDailySource`` 是组合源（各方法取实测最稳后端）。
    """

    name: str

    def fetch_hist(self, code: str, *, start: str, end: str, adjust: str = "") -> Any: ...
    def fetch_index(self, code: str, *, start: str, end: str) -> Any: ...
    def fetch_calendar(self) -> list[str]: ...
    def fetch_code_list(self) -> list[str]: ...
    def fetch_delisted_codes(self) -> Any: ...
    def fetch_delisted_daily(self, code: str, *, start: str, end: str) -> Any: ...
    def fetch_spot(self) -> Any: ...


@runtime_checkable
class EnrichSource(Protocol):
    """个股 enrich 数据源规范（盘口/资金流/概念/分钟K 的原子拉取）。

    只负责"取数"（含归一化与单点错误兜底）；concept 三级 cache fallback、io_tasks
    并发、jbxx/concept cache、archive 读写等编排留在 ``services/enrich.py`` facade。

    注：``fetch_concept_fit_rank`` 与 ``fetch_stock_concepts`` 只做原始拉取（无缓存、
    不兜底），错误由 ``services/enrich.py`` 的 cache wrapper 统一处理——这样才能保留
    原两级 cache（粘合度 / 问财概念）与 ``概念粘合度`` 富数据。
    """

    name: str

    def fetch_stock_quote(self, symbol: str) -> Any: ...
    def fetch_stock_fund_flow(self, symbol: str) -> Any: ...
    def fetch_stock_fund_flow_daily(self, symbol: str, *, days: int = 10) -> Any: ...
    def fetch_concept_fit_rank(self, symbol: str) -> Any: ...
    def fetch_stock_concepts(self, symbol: str, *, name: str | None = None) -> Any: ...
    def fetch_stock_minute(self, symbol: str, *, context: str = "") -> Any: ...


@runtime_checkable
class MarketSource(Protocol):
    """运维行情数据源规范（五时段 payload 的市场宏观拉取）。

    只负责"取数"（含多源 fallback 策略）；业务编排（标的池过滤/涨停高度/人气榜
    prefilter/概念板解包）留在 ``tools/market.py`` facade。
    """

    name: str

    def fetch_index_spot(self) -> Any: ...
    def fetch_zqxy(self, *, market_phase: str = "intraday") -> Any: ...
    def fetch_ztgk_pool(self) -> Any: ...
    def fetch_ztgk_prev(self, date: str) -> Any: ...
    def fetch_hot_raw(self, limit: int) -> Any: ...
    def fetch_concept_boards(self) -> Any: ...
    def fetch_industry_board(self, context: str, sort_key: str, desc: bool = True) -> Any: ...
    def fetch_market_fund_flow(self, n: int) -> Any: ...
    def fetch_ths_rank_screen(self, kind: str, *, symbol: str | None = None) -> Any: ...
    def fetch_em_industry_map(self) -> Any: ...
    def fetch_em_hot_rank(self) -> Any: ...
    def fetch_em_concept_boards(self) -> Any: ...
    def fetch_stop_resume(self, date: str) -> Any: ...
    def fetch_industry_map(self) -> Any: ...


@runtime_checkable
class InfoSource(Protocol):
    """资讯/基本信息数据源规范（全局新闻 + 个股基本信息）。

    只负责"取数"；新闻 payload 封装、jbxx 周文件缓存等编排在调用方。

    注：人气榜（hot）归 ``MarketSource.fetch_hot_raw``、问财概念（wencai）归
    ``EnrichSource.fetch_stock_concepts``，故不在此重复，避免协议重叠。
    """

    name: str

    def fetch_news(self) -> Any: ...
    def fetch_stock_info(self, symbol: str) -> Any: ...
